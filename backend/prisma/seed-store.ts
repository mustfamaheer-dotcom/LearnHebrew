async function main() {
  console.log('Seeding Gamification Store permissions and all 28 store items...');

  const roles = await prisma.roleDefinition.findMany();
  const roleByName = new Map(roles.map((r) => [r.name, r]));

  for (const perm of STORE_PERMISSIONS) {
    const upsertedPerm = await prisma.permission.upsert({
      where: { code: perm.code },
      update: {
        group: perm.group,
        description: perm.description,
      },
      create: {
        code: perm.code,
        group: perm.group,
        description: perm.description,
      },
    });

    for (const roleName of perm.roles) {
      const role = roleByName.get(roleName);
      if (!role) continue;
      await prisma.rolePermission.upsert({
        where: {
          roleId_permissionId: {
            roleId: role.id,
            permissionId: upsertedPerm.id,
          },
        },
        update: { granted: true },
        create: {
          roleId: role.id,
          permissionId: upsertedPerm.id,
          granted: true,
        },
      });
    }
  }

  console.log(`Upserted ${STORE_PERMISSIONS.length} store permissions & role mappings.`);

  // Remove deprecated unstyled starter item if unredeemed
  const deprecated = await prisma.storeItem.findFirst({
    where: { nameEn: 'Sky Scholar Name' },
    include: { _count: { select: { redemptions: true } } },
  });
  if (deprecated && deprecated._count.redemptions === 0) {
    await prisma.storeItem.delete({ where: { id: deprecated.id } });
  }

  let createdCount = 0;
  let updatedCount = 0;

  for (const item of STARTER_STORE_ITEMS) {
    const existing = await prisma.storeItem.findFirst({
      where: { nameEn: item.nameEn },
      select: { id: true },
    });

    if (existing) {
      await prisma.storeItem.update({
        where: { id: existing.id },
        data: item,
      });
      updatedCount++;
    } else {
      await prisma.storeItem.create({
        data: item,
      });
      createdCount++;
    }
  }

  const totalItems = await prisma.storeItem.count();
  const frameCount = await prisma.storeItem.count({ where: { type: StoreItemType.AVATAR_FRAME } });
  const nicknameCount = await prisma.storeItem.count({ where: { type: StoreItemType.NICKNAME } });
  console.log(
    `StoreItems synced: ${createdCount} created, ${updatedCount} updated. Total in DB: ${totalItems} (${frameCount} frames, ${nicknameCount} nicknames).`
  );
  console.log('Gamification Store seed complete!');
}

main()
  .catch((e) => {
    console.error('Store seed failed:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
